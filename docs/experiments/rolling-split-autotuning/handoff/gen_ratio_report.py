def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--manifest", required=True,
                    help='REQUIRED JSON of EXPLICIT run paths (no glob): {"q": {"ratio": DIR, '
                         '"off": {"mpb": DIR, ...}, "clean": {"mpb": DIR}}}. Every query in --queries must '
                         'have an entry. Pass the exact dirs from the benchmark run.')
    ap.add_argument("--queries", default="cs03 csH csH3 pv03g")
    ap.add_argument("--out", default="docs/experiments/rolling-split-autotuning/results/ratio-real-report.html")
    ap.add_argument("--force", action="store_true", help="allow overwriting an existing --out file")
    a=ap.parse_args()
    if os.path.exists(a.out) and not a.force:
        raise SystemExit(f"REFUSING to overwrite existing {a.out} (pass --force or choose a new --out)")
    manifest=json.load(open(a.manifest))
    arms={q: build_arms(q, manifest) for q in a.queries.split()}                  # explicit paths per query, no glob
    rows=[]
    for q in a.queries.split():
        off_arms, ratio_dir, _ = arms[q]
        r=row(off_arms, ratio_dir, q)
        if r: rows.append(r); print(f"  {q}: split={r['split']} wall={r['wall']:.1f}s dWall={fpct(r['dW'])} worst band={r['ov'][0]}")
        else: print(f"  {q}: SKIP (incomplete — need OFF sweep + ratio arm with event logs)")
    imgs={}
    for r in rows:
        off_arms, ratio_dir, clean_arms = arms[r['q']]
        try: imgs[r['q']]=make_plot_b64(off_arms, ratio_dir, clean_arms, r['q'])
        except Exception as ex: print(f"  plot {r['q']}: {ex}")
    ptsplits={}
    for r in rows:
        _, ratio_dir, _ = arms[r['q']]
        el=eventlog(ratio_dir)
        if el and os.path.exists(el): ptsplits[r['q']]=per_table_splits(el)
    open(a.out,"w").write(render(rows, imgs, ptsplits))
    print(f"wrote {a.out} ({os.path.getsize(a.out)} bytes; {len(rows)} queries)")

if __name__=="__main__": main()
